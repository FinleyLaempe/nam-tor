//! Candidate quirks entry emission and PR contribution helpers.
//!
//! After `run_probe` identifies an emitter control, these functions render a
//! TOML entry ready for upstream contribution and a redacted report that
//! contains no biometric data. The `verified_by` field is always
//! `"namtor-probe"` — a human contributor replaces it with their name before
//! submitting.

use std::path::Path;

use namtor_hwdb::quirks::EmitterMethod;

use crate::probe::ProbeResult;

/// Renders a candidate quirks entry as TOML, matching the `QuirksEntry` schema
/// so it round-trips through `toml::from_str::<QuirksEntry>`.
///
/// `name` is the human-readable device name (e.g. from `lsusb`). Fields the
/// probe cannot fill (`ir_vc_interface`, `ir_format_guid`, etc.) are emitted as
/// placeholders for a human to complete from `namtor-probe describe` output.
pub fn render_quirks_entry(result: &ProbeResult, name: &str) -> String {
    let method_str = method_to_str(result.method);
    let payload_on = hex_payload(&result.payload_on);
    let payload_off = hex_payload(&result.payload_off);

    let mut out = String::new();
    out.push_str("# SPDX-License-Identifier: Apache-2.0\n");
    out.push_str("# Candidate quirks entry generated by namtor-probe.\n");
    out.push_str("# Review and fill TODO fields before submitting.\n\n");

    out.push_str("[device]\n");
    out.push_str(&format!("vid_pid = \"{}\"\n", result.vid_pid));
    out.push_str(&format!("name = \"{name}\"\n\n"));

    out.push_str("[nodes]\n");
    out.push_str("ir_vc_interface = 0\n");
    out.push_str("ir_streaming = 0\n");
    out.push_str("ir_format_guid = \"\"\n");
    out.push_str("metadata_node = false\n");
    out.push_str("depth = false\n\n");

    out.push_str("[emitter]\n");
    out.push_str(&format!("method = \"{method_str}\"\n"));
    out.push_str(&format!("unit = {}\n", result.unit));
    out.push_str(&format!("selector = {}\n", result.selector));
    out.push_str(&format!("payload_on = \"{payload_on}\"\n"));
    out.push_str(&format!("payload_off = \"{payload_off}\"\n"));
    if let Some(m) = result.mode {
        out.push_str(&format!("mode = {m}\n"));
    }
    out.push('\n');

    out.push_str("[meta]\n");
    out.push_str("verified_by = \"namtor-probe\"\n");
    out.push_str("verified_on = \"TODO\"\n");
    out.push_str("kernel = \"TODO\"\n");

    out
}

/// Builds the `gh pr create` shell invocation for contributing the entry.
///
/// The vid:pid is parsed from the entry filename (`3277-0018.toml` →
/// `3277:0018`), matching the `quirks/devices/` naming convention.
pub fn gh_pr_create_invocation(entry_path: &Path) -> String {
    let stem = entry_path
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or("unknown");
    let vid_pid = stem.replacen('-', ":", 1);
    format!(
        "gh pr create --title \"quirks: add {vid_pid}\" --body \"Candidate quirks entry for {vid_pid} generated by namtor-probe. See {path}.\"",
        path = entry_path.display()
    )
}

/// Renders a human-readable probe report with no biometric data.
///
/// The words "frame" and "image" never appear — the report describes the
/// control discovery, not the capture pipeline.
pub fn render_redacted_report(result: &ProbeResult) -> String {
    let mut out = String::new();
    out.push_str(&format!("device: {}\n", result.vid_pid));
    out.push_str(&format!("method: {}\n", method_to_str(result.method)));
    out.push_str(&format!("unit: {}\n", result.unit));
    out.push_str(&format!("selector: {}\n", result.selector));
    if let Some(m) = result.mode {
        out.push_str(&format!("mode: {m}\n"));
    }
    out.push_str(&format!(
        "payload_on: {}\n",
        hex_payload(&result.payload_on)
    ));
    out.push_str(&format!(
        "payload_off: {}\n",
        hex_payload(&result.payload_off)
    ));
    out.push_str(&format!("evidence: {}\n", result.evidence));
    out
}

fn method_to_str(m: EmitterMethod) -> &'static str {
    match m {
        EmitterMethod::MsxuMode => "msxu_mode",
        EmitterMethod::Msxu => "msxu",
        EmitterMethod::VendorXu => "vendor_xu",
        EmitterMethod::AlwaysOn => "always_on",
        EmitterMethod::FirmwareStrobed => "firmware_strobed",
        EmitterMethod::Unknown => "unknown",
    }
}

fn hex_payload(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample_result() -> ProbeResult {
        ProbeResult {
            vid_pid: "3277:0018".to_string(),
            method: EmitterMethod::MsxuMode,
            unit: 4,
            selector: 6,
            payload_on: vec![0x01, 0x03, 0x02, 0, 0, 0, 0, 0, 0],
            payload_off: vec![0x01, 0x03, 0x01, 0, 0, 0, 0, 0, 0],
            mode: Some(2),
            evidence: "MSXU mode 2 alternation 81.8 (on 41.0 / off 0.1)".to_string(),
        }
    }

    #[test]
    fn renders_quirks_entry_with_required_fields() {
        let toml = render_quirks_entry(&sample_result(), "Sonix USB2.0 FHD UVC WebCam");

        assert!(toml.contains("vid_pid = \"3277:0018\""));
        assert!(toml.contains("method = \"msxu_mode\""));
        assert!(toml.contains("selector = 6"));
        assert!(toml.contains("payload_on = \"010302000000000000\""));
        assert!(toml.contains("verified_by = \"namtor-probe\""));
    }

    #[test]
    fn rendered_entry_round_trips_through_quirks_entry() {
        let toml = render_quirks_entry(&sample_result(), "Sonix USB2.0 FHD UVC WebCam");

        let entry: namtor_hwdb::quirks::QuirksEntry =
            toml::from_str(&toml).expect("rendered TOML must parse as QuirksEntry");

        assert_eq!(entry.device.vid_pid, "3277:0018");
        assert_eq!(entry.emitter.method, EmitterMethod::MsxuMode);
        assert_eq!(entry.emitter.unit, Some(4));
        assert_eq!(entry.emitter.selector, Some(6));
        assert_eq!(
            entry.emitter.payload_on,
            vec![0x01, 0x03, 0x02, 0, 0, 0, 0, 0, 0]
        );
        assert_eq!(entry.emitter.mode, Some(2));
        assert_eq!(entry.meta.verified_by, "namtor-probe");
    }

    #[test]
    fn gh_pr_create_invocation_contains_command_and_vid_pid() {
        let path = std::path::Path::new("quirks/devices/3277-0018.toml");
        let cmd = gh_pr_create_invocation(path);

        assert!(cmd.contains("gh pr create"));
        assert!(cmd.contains("3277:0018"));
    }

    #[test]
    fn redacted_report_contains_no_biometric_terms() {
        let report = render_redacted_report(&sample_result());

        let lower = report.to_lowercase();
        assert!(!lower.contains("frame"), "report must not mention 'frame'");
        assert!(!lower.contains("image"), "report must not mention 'image'");
        assert!(report.contains("3277:0018"));
        assert!(report.contains("msxu_mode"));
    }
}
