#!/usr/bin/env python3
"""Train MiniFASNet PAD model on synthetic strobe-differential data.

Spec §6.4 + §10.3: MiniFASNet-class CNN trained on D = On − Off strobe
differentials. Without collected data, we generate physics-based synthetic
differentials that encode the same signals the analytic gates check:

Live (bonafide):
  - Strong positive D (emitter illuminates skin)
  - 1/r² radial falloff (nose nearer than ears)
  - Specular hotspot (compact bright region)
  - Subsurface scattering (smooth low-frequency gradient field)

Spoof:
  - Screen replay: near-zero D (panels emit ~nothing at 850 nm)
  - Print: weak/flat D (IR-transparent inks), no subsurface scattering
  - Cutout mask: uniform D, no radial falloff

The model is a small CNN (MiniFASNet-class, <100K params) that takes an
80×80 greyscale differential as input and outputs live/spoof logits.
Exported to ONNX for the namtor-worker inference path.

This script is **synthetic-only** (see `--synthetic-only` flag, on by
default). Subject-disjoint and device-disjoint evaluation splits are
generated by partitioning the synthetic seed space: each synthetic
"subject" is a deterministic RNG stream keyed by a subject id, and each
"device" is a global gain/offset perturbation applied across all of that
subject's samples. No real biometric data is read or written.

Outputs:
  - ONNX model at `--out`
  - SHA-256 of the ONNX bytes printed to stdout (for ModelSpec.sha256)
  - Deterministic model card at `<out>.card.json`

Usage:
    python3 ml/recipes/train_pad.py --epochs 50 --out ml/models/minifasnet_pad.onnx
"""

import argparse
import hashlib
import json
import math
import os
import sys
from dataclasses import asdict, dataclass
from pathlib import Path

import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F
from torch.utils.data import DataLoader, TensorDataset


# ---------------------------------------------------------------------------
# MiniFASNet architecture (§10.3: MiniFASNet-class, <100K params)
# ---------------------------------------------------------------------------

class DepthwiseSeparableConv(nn.Module):
    def __init__(self, in_ch, out_ch, stride=1):
        super().__init__()
        self.depthwise = nn.Conv2d(in_ch, in_ch, 3, stride=stride, padding=1, groups=in_ch, bias=False)
        self.pointwise = nn.Conv2d(in_ch, out_ch, 1, bias=False)
        self.bn = nn.BatchNorm2d(out_ch)

    def forward(self, x):
        x = self.depthwise(x)
        x = self.pointwise(x)
        x = self.bn(x)
        return F.relu6(x)


class MiniFASNet(nn.Module):
    """Small CNN for PAD on 80×80 strobe differentials. ~80K params."""

    def __init__(self, num_classes=2):
        super().__init__()
        self.features = nn.Sequential(
            nn.Conv2d(1, 16, 3, stride=2, padding=1, bias=False),
            nn.BatchNorm2d(16),
            nn.ReLU6(inplace=True),

            DepthwiseSeparableConv(16, 32, stride=2),
            DepthwiseSeparableConv(32, 32, stride=1),
            DepthwiseSeparableConv(32, 64, stride=2),
            DepthwiseSeparableConv(64, 64, stride=1),
            DepthwiseSeparableConv(64, 128, stride=2),
            DepthwiseSeparableConv(128, 128, stride=1),
        )
        self.gap = nn.AdaptiveAvgPool2d(1)
        self.classifier = nn.Linear(128, num_classes)

    def forward(self, x):
        x = self.features(x)
        x = self.gap(x)
        x = x.view(x.size(0), -1)
        x = self.classifier(x)
        return x


# ---------------------------------------------------------------------------
# Synthetic data generation (physics-based, spec §6.4)
# ---------------------------------------------------------------------------

def make_live_differential(size=80, rng=None):
    """Simulate a live face strobe differential: 1/r² falloff + specular + subsurface."""
    if rng is None:
        rng = np.random.default_rng()

    cx = size / 2 + rng.normal(0, 3)
    cy = size / 2 + rng.normal(0, 3)
    a = rng.uniform(3000, 8000)
    b = rng.uniform(3, 8)

    yy, xx = np.meshgrid(np.arange(size), np.arange(size), indexing='ij')
    r = np.sqrt((xx - cx) ** 2 + (yy - cy) ** 2)
    img = a / (r + b) ** 2

    # Specular hotspot
    spx, spy = cx + rng.normal(0, 5), cy + rng.normal(0, 5)
    sp_r = np.sqrt((xx - spx) ** 2 + (yy - spy) ** 2)
    img += rng.uniform(50, 150) * np.exp(-sp_r ** 2 / (2 * rng.uniform(2, 5) ** 2))

    # Subsurface scattering: smooth low-frequency modulation
    img += rng.uniform(-10, 10) * np.sin(xx * 0.1) * np.cos(yy * 0.1)

    # Noise
    img += rng.normal(0, 3, img.shape)

    return np.clip(img, 0, 255).astype(np.float32)


def make_screen_replay_differential(size=80, rng=None):
    """Screen replay: near-zero D (panels emit ~nothing at 850 nm)."""
    if rng is None:
        rng = np.random.default_rng()
    img = rng.normal(0, 2, (size, size))
    return np.clip(img, 0, 255).astype(np.float32)


def make_print_differential(size=80, rng=None):
    """Print: weak, flat D (IR-transparent inks), no subsurface scattering."""
    if rng is None:
        rng = np.random.default_rng()
    base = rng.uniform(2, 15)
    img = np.full((size, size), base, dtype=np.float32)
    img += rng.normal(0, 5, img.shape)
    return np.clip(img, 0, 255).astype(np.float32)


def make_cutout_differential(size=80, rng=None):
    """Cutout mask: uniform illumination, no radial falloff."""
    if rng is None:
        rng = np.random.default_rng()
    base = rng.uniform(20, 50)
    img = np.full((size, size), base, dtype=np.float32)
    # Slight vignetting (lens, not face geometry)
    cy, cx = size / 2, size / 2
    yy, xx = np.meshgrid(np.arange(size), np.arange(size), indexing='ij')
    r = np.sqrt((xx - cx) ** 2 + (yy - cy) ** 2)
    img *= 1 - 0.1 * (r / (size / 2)) ** 2
    img += rng.normal(0, 4, img.shape)
    return np.clip(img, 0, 255).astype(np.float32)


def generate_dataset(n_per_class=12500, size=80, seed=42, n_subjects=125):
    """Generate a balanced synthetic dataset: 25K live + 25K spoof (4 spoof types).

    Returns `(X, y, subject_ids)` where `subject_ids[i]` is the synthetic
    subject id of sample `i` ∈ `[0, n_subjects)`. Each subject's samples are
    drawn from a deterministic RNG stream keyed by `(subject_id, class)`, so
    subject-disjoint splits are reproducible: a subject appears in exactly
    one of train / val / test, never both.
    """
    root_rng = np.random.default_rng(seed)
    n_spoof_per_type = n_per_class // 3

    def subject_rng(subject_id: int, label: int) -> np.random.Generator:
        # Seed mixes root seed + subject id + label so two subjects (or the
        # same subject across classes) get independent streams.
        return np.random.default_rng(seed * 2**24 + subject_id * 4 + label)

    # Distribute samples across subjects round-robin.
    def make_live(subject_id: int) -> np.ndarray:
        rng = subject_rng(subject_id, 0)
        return make_live_differential(size, rng)

    def make_screen(subject_id: int) -> np.ndarray:
        rng = subject_rng(subject_id, 1)
        return make_screen_replay_differential(size, rng)

    def make_print(subject_id: int) -> np.ndarray:
        rng = subject_rng(subject_id, 2)
        return make_print_differential(size, rng)

    def make_cutout(subject_id: int) -> np.ndarray:
        rng = subject_rng(subject_id, 3)
        return make_cutout_differential(size, rng)

    live_imgs = []
    live_subs = []
    for i in range(n_per_class):
        sid = i % n_subjects
        live_imgs.append(make_live(sid))
        live_subs.append(sid)

    spoof_imgs = []
    spoof_subs = []
    for i in range(n_spoof_per_type):
        sid = i % n_subjects
        spoof_imgs.append(make_screen(sid))
        spoof_subs.append(sid)
    for i in range(n_spoof_per_type):
        sid = (i + n_spoof_per_type) % n_subjects
        spoof_imgs.append(make_print(sid))
        spoof_subs.append(sid)
    for i in range(n_spoof_per_type):
        sid = (i + 2 * n_spoof_per_type) % n_subjects
        spoof_imgs.append(make_cutout(sid))
        spoof_subs.append(sid)

    X = np.stack(live_imgs + spoof_imgs).astype(np.float32) / 255.0
    X = X[:, np.newaxis, :, :]
    y = np.concatenate([
        np.zeros(len(live_imgs), dtype=np.int64),
        np.ones(len(spoof_imgs), dtype=np.int64),
    ])
    subjects = np.array(live_subs + spoof_subs, dtype=np.int64)

    perm = root_rng.permutation(len(X))
    X, y, subjects = X[perm], y[perm], subjects[perm]
    return torch.from_numpy(X), torch.from_numpy(y), torch.from_numpy(subjects)


# ---------------------------------------------------------------------------
# Training
# ---------------------------------------------------------------------------

def subject_disjoint_split(subjects, n_subjects, val_subjects, test_subjects, seed=42):
    """Subject-disjoint split: partition subject ids into train/val/test sets.

    No subject appears in more than one split. Returns boolean masks into the
    sample array. `val_subjects + test_subjects` must be `< n_subjects`.
    """
    rng = np.random.default_rng(seed)
    perm = rng.permutation(n_subjects)
    val_ids = set(perm[:val_subjects].tolist())
    test_ids = set(perm[val_subjects : val_subjects + test_subjects].tolist())
    train_ids = set(perm[val_subjects + test_subjects :].tolist())

    s = subjects.numpy()
    train_mask = np.array([sid in train_ids for sid in s], dtype=bool)
    val_mask = np.array([sid in val_ids for sid in s], dtype=bool)
    test_mask = np.array([sid in test_ids for sid in s], dtype=bool)
    return train_mask, val_mask, test_mask


def apply_device_perturbation(X: torch.Tensor, subjects: torch.Tensor, n_subjects: int, seed: int):
    """Apply a per-subject (synthetic "device") gain/offset perturbation.

    Models the device-disjoint axis: each subject's frames are captured on
    the same hypothetical device, so a device-disjoint split is the same
    partition as the subject-disjoint split (subject id ≡ device id here).
    The perturbation is a fixed per-subject `(gain, offset)` pair drawn
    once and applied to every sample of that subject.
    """
    rng = np.random.default_rng(seed + 7777)
    gain = 1.0 + rng.normal(0, 0.05, n_subjects).astype(np.float32)
    offset = rng.normal(0, 0.02, n_subjects).astype(np.float32)
    s = subjects.numpy()
    Xnp = X.numpy()
    for sid in range(n_subjects):
        m = s == sid
        if m.any():
            Xnp[m] = Xnp[m] * gain[sid] + offset[sid]
    return torch.from_numpy(np.clip(Xnp, 0.0, 1.0))


@dataclass(frozen=True)
class ModelCard:
    """Deterministic model card written next to the ONNX file."""

    model_id: str
    architecture: str
    num_params: int
    input_shape: list
    num_classes: int
    training_data: str
    synthetic_only: bool
    n_subjects: int
    split: dict
    best_val_acc: float
    test_acc: float
    onnx_sha256: str
    onnx_path: str
    license: str


def train_model(
    epochs=50,
    batch_size=256,
    lr=1e-3,
    device='cuda',
    seed=42,
    n_subjects=125,
    synthetic_only=True,
    val_subjects=15,
    test_subjects=15,
):
    torch.manual_seed(seed)
    dev = torch.device(device if torch.cuda.is_available() else 'cpu')
    print(f"Device: {dev}")

    print("Generating synthetic dataset...")
    X, y, subjects = generate_dataset(seed=seed, n_subjects=n_subjects)
    print(
        f"Dataset: {X.shape}, {y.shape}, live={int((y==0).sum())}, "
        f"spoof={int((y==1).sum())}, subjects={n_subjects}"
    )

    if not synthetic_only:
        raise SystemExit(
            "Refusing to train on non-synthetic data: real biometric PAD "
            "data requires recorded consent (CONTRIBUTING.md) and is out of "
            "scope for this recipe. Pass --synthetic-only (default)."
        )

    # Device-disjoint perturbation (applied before splitting, per subject).
    X = apply_device_perturbation(X, subjects, n_subjects, seed)

    # Subject-disjoint (== device-disjoint in this synthetic setup) split.
    train_mask, val_mask, test_mask = subject_disjoint_split(
        subjects, n_subjects, val_subjects=val_subjects, test_subjects=test_subjects, seed=seed
    )
    X_train, y_train = X[train_mask], y[train_mask]
    X_val, y_val = X[val_mask], y[val_mask]
    X_test, y_test = X[test_mask], y[test_mask]
    print(
        f"Split: train={int(train_mask.sum())} val={int(val_mask.sum())} "
        f"test={int(test_mask.sum())} (subject-disjoint + device-disjoint)"
    )

    train_ds = TensorDataset(X_train, y_train)
    val_ds = TensorDataset(X_val, y_val)
    train_dl = DataLoader(train_ds, batch_size=batch_size, shuffle=True, num_workers=0)
    val_dl = DataLoader(val_ds, batch_size=batch_size, shuffle=False, num_workers=0)

    model = MiniFASNet(num_classes=2).to(dev)
    n_params = sum(p.numel() for p in model.parameters())
    print(f"Model: MiniFASNet, {n_params} params")

    optimizer = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=1e-4)
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=epochs)
    criterion = nn.CrossEntropyLoss()

    best_val_acc = 0.0
    best_state = None

    for epoch in range(epochs):
        model.train()
        train_loss = 0.0
        train_correct = 0
        train_total = 0

        for xb, yb in train_dl:
            xb, yb = xb.to(dev), yb.to(dev)
            optimizer.zero_grad()
            out = model(xb)
            loss = criterion(out, yb)
            loss.backward()
            optimizer.step()

            train_loss += loss.item() * xb.size(0)
            train_correct += (out.argmax(1) == yb).sum().item()
            train_total += xb.size(0)

        scheduler.step()

        model.eval()
        val_loss = 0.0
        val_correct = 0
        val_total = 0
        with torch.no_grad():
            for xb, yb in val_dl:
                xb, yb = xb.to(dev), yb.to(dev)
                out = model(xb)
                loss = criterion(out, yb)
                val_loss += loss.item() * xb.size(0)
                val_correct += (out.argmax(1) == yb).sum().item()
                val_total += xb.size(0)

        train_acc = train_correct / train_total
        val_acc = val_correct / val_total
        print(f"Epoch {epoch+1:3d}/{epochs}: train_loss={train_loss/train_total:.4f} train_acc={train_acc:.4f} val_loss={val_loss/val_total:.4f} val_acc={val_acc:.4f}")

        if val_acc > best_val_acc:
            best_val_acc = val_acc
            best_state = {k: v.clone() for k, v in model.state_dict().items()}

    print(f"\nBest val accuracy: {best_val_acc:.4f}")
    model.load_state_dict(best_state)

    # Held-out test accuracy on the subject-disjoint test split.
    model.eval()
    test_correct = 0
    test_total = 0
    with torch.no_grad():
        test_dl = DataLoader(TensorDataset(X_test, y_test), batch_size=batch_size, shuffle=False)
        for xb, yb in test_dl:
            xb, yb = xb.to(dev), yb.to(dev)
            out = model(xb)
            test_correct += (out.argmax(1) == yb).sum().item()
            test_total += xb.size(0)
    test_acc = test_correct / max(test_total, 1)
    print(f"Subject-disjoint test accuracy: {test_acc:.4f}")

    split_info = {
        "n_subjects": n_subjects,
        "val_subjects": val_subjects,
        "test_subjects": test_subjects,
        "train_subjects": n_subjects - val_subjects - test_subjects,
        "disjoint_axis": "subject == device (synthetic)",
    }
    return model, best_val_acc, test_acc, n_params, split_info


def export_onnx(model, path, size=80):
    """Export the model to ONNX and return the SHA-256 of the .onnx bytes."""
    model.eval()
    model_cpu = model.cpu()
    dummy = torch.randn(1, 1, size, size)
    torch.onnx.export(
        model_cpu,
        dummy,
        path,
        input_names=["input"],
        output_names=["logits"],
        dynamic_axes={"input": {0: "batch"}, "logits": {0: "batch"}},
        opset_version=14,
    )
    sha = hashlib.sha256(Path(path).read_bytes()).hexdigest()
    print(f"Exported ONNX model to {path}")
    print(f"ONNX sha256: {sha}")
    return sha


def write_model_card(path: Path, card: ModelCard) -> None:
    """Write the model card as deterministic JSON next to the ONNX file."""
    card_path = path.with_suffix(path.suffix + ".card.json")
    card_path.write_text(json.dumps(asdict(card), indent=2, sort_keys=True) + "\n")
    print(f"Wrote model card to {card_path}")


def main():
    parser = argparse.ArgumentParser(description="Train MiniFASNet PAD model")
    parser.add_argument("--epochs", type=int, default=50)
    parser.add_argument("--batch-size", type=int, default=256)
    parser.add_argument("--lr", type=float, default=1e-3)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--device", type=str, default="cuda")
    parser.add_argument("--out", type=str, default="ml/models/minifasnet_pad.onnx")
    parser.add_argument(
        "--n-subjects",
        type=int,
        default=125,
        help="Number of synthetic subjects (subject-disjoint split axis).",
    )
    parser.add_argument(
        "--val-subjects",
        type=int,
        default=15,
        help="Number of subjects reserved for the validation split.",
    )
    parser.add_argument(
        "--test-subjects",
        type=int,
        default=15,
        help="Number of subjects reserved for the held-out test split.",
    )
    parser.add_argument(
        "--synthetic-only",
        action="store_true",
        default=True,
        help="Refuse to train on non-synthetic data (default: True).",
    )
    parser.add_argument(
        "--allow-real-data",
        action="store_true",
        default=False,
        help="Escape hatch: would allow real biometric data. Currently refused "
        "regardless — consent-gated collection (§10.4) is a separate path.",
    )
    args = parser.parse_args()

    synthetic_only = args.synthetic_only and not args.allow_real_data
    model, val_acc, test_acc, n_params, split_info = train_model(
        epochs=args.epochs,
        batch_size=args.batch_size,
        lr=args.lr,
        device=args.device,
        seed=args.seed,
        n_subjects=args.n_subjects,
        synthetic_only=synthetic_only,
        val_subjects=args.val_subjects,
        test_subjects=args.test_subjects,
    )

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    sha = export_onnx(model, str(out_path))

    card = ModelCard(
        model_id="minifasnet_pad",
        architecture="MiniFASNet (depthwise-separable CNN, GAP, linear classifier)",
        num_params=int(n_params),
        input_shape=[1, 1, 80, 80],
        num_classes=2,
        training_data="physics-based synthetic strobe differentials (§6.4)",
        synthetic_only=True,
        n_subjects=args.n_subjects,
        split=split_info,
        best_val_acc=float(val_acc),
        test_acc=float(test_acc),
        onnx_sha256=sha,
        onnx_path=str(out_path),
        license="self-trained, no upstream licence constraints",
    )
    write_model_card(out_path, card)

    print(f"\nDone. Val accuracy: {val_acc:.4f}, test accuracy: {test_acc:.4f}")
    print(f"Model saved to: {out_path}")
    print(f"SHA-256: {sha}")


if __name__ == "__main__":
    main()
